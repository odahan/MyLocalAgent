using System.Windows.Media.Imaging;
using System.IO;
using OD.MyLocalAgent.Core;

namespace OD.MyLocalAgent.UI.ViewModels;

/// <summary>Projects one ordered Direct Chat content part for WPF rendering.</summary>
public sealed class DirectChatContentItem
{
    /// <summary>Initializes a display item.</summary>
    public DirectChatContentItem(DirectChatContent content)
    {
        Content = content ?? throw new ArgumentNullException(nameof(content));
        if (content.Kind == DirectChatContentKind.Image && content.Data is not null)
        {
            using var stream = new MemoryStream(content.Data, writable: false);
            var image = new BitmapImage();
            image.BeginInit();
            image.CacheOption = BitmapCacheOption.OnLoad;
            image.StreamSource = stream;
            image.EndInit();
            image.Freeze();
            ImageSource = image;
        }
    }

    /// <summary>Gets the persisted content.</summary>
    public DirectChatContent Content { get; }

    /// <summary>Gets text content.</summary>
    public string Text => Content.Text ?? string.Empty;

    /// <summary>Gets the image preview.</summary>
    public BitmapSource? ImageSource { get; }

    /// <summary>Gets whether this is text.</summary>
    public bool IsText => Content.Kind == DirectChatContentKind.Text;

    /// <summary>Gets whether this is an image.</summary>
    public bool IsImage => Content.Kind == DirectChatContentKind.Image;

    /// <summary>Gets whether this is audio.</summary>
    public bool IsAudio => Content.Kind == DirectChatContentKind.Audio;

    /// <summary>Gets provider-origin disclosure text.</summary>
    public string CloudDisclosure => Content.IsCloudContent
        ? $"Generated by cloud provider {Content.ProviderName ?? "unknown"}"
        : string.Empty;

    /// <summary>Gets a short duration label.</summary>
    public string DurationText => Content.Duration is null
        ? string.Empty
        : Content.Duration.Value.TotalHours >= 1
            ? Content.Duration.Value.ToString(@"h\:mm\:ss")
            : Content.Duration.Value.ToString(@"m\:ss");

    /// <summary>Gets a readable persisted size.</summary>
    public string SizeText => Content.SizeBytes >= 1024 * 1024
        ? $"{Content.SizeBytes / 1024d / 1024d:F1} MiB"
        : $"{Math.Max(1, Content.SizeBytes / 1024d):F0} KiB";
}
