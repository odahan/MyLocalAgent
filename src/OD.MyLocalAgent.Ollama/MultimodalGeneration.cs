namespace OD.MyLocalAgent.Ollama;

/// <summary>Declares provider capabilities without inferring them from protocol compatibility.</summary>
[Flags]
public enum ProviderCapabilities
{
    /// <summary>No declared capability.</summary>
    None = 0,

    /// <summary>Text chat generation.</summary>
    TextChat = 1,

    /// <summary>Image input in chat context.</summary>
    ImageInput = 2,

    /// <summary>Image generation output.</summary>
    ImageOutput = 4,

    /// <summary>Audio generation output.</summary>
    AudioOutput = 8,

    /// <summary>Reserved for future video generation.</summary>
    VideoOutput = 16,
}

/// <summary>Identifies a non-chat generation operation.</summary>
public enum MultimodalGenerationKind
{
    /// <summary>Generate an image from text.</summary>
    Image,

    /// <summary>Generate speech audio from text.</summary>
    Audio,
}

/// <summary>Describes a provider-neutral media generation request.</summary>
public sealed record MultimodalGenerationRequest
{
    /// <summary>Gets the requested output kind.</summary>
    public required MultimodalGenerationKind Kind { get; init; }

    /// <summary>Gets the text prompt or text to speak.</summary>
    public required string Prompt { get; init; }
}

/// <summary>Describes one generated binary media result.</summary>
public sealed record MultimodalGenerationResult
{
    /// <summary>Gets the output kind.</summary>
    public required MultimodalGenerationKind Kind { get; init; }

    /// <summary>Gets the MIME type.</summary>
    public required string MediaType { get; init; }

    /// <summary>Gets the suggested file name.</summary>
    public required string FileName { get; init; }

    /// <summary>Gets the complete generated bytes.</summary>
    public required byte[] Data { get; init; }

    /// <summary>Gets the duration when known.</summary>
    public TimeSpan? Duration { get; init; }
}
